# Writes Data.lua from a saved copy of https://foreverchanges.pro/professions/cooking
#
#   curl -sL -A "Mozilla/5.0" -o cooking.html https://foreverchanges.pro/professions/cooking
#   python tools/gen_data.py cooking.html Data.lua
#
# The page is a Next.js page: its data sits in self.__next_f.push([1,"..."]) chunks, as JSON inside JS
# string literals. Two things are taken from it: "rows" (one entry per recipe: the spell, the dish, the
# skill colours, the recipe item, where that comes from) and "items" (names and icons by item id).
#
# What the page leaves open is filled by hand in OVERRIDES below, each marked as taken from Classic.
# Not shipped to players (.pkgmeta ignores tools/).
import json
import re
import sys
import datetime

SIDE = {"a": "A", "h": "H"}

# Recipes the page lists without a source, whose Classic source is well known. classic = True marks the
# entry "as in Classic, not confirmed for Forever" in the window.
OVERRIDES = {
    13028: {"taught": {"npc": "Henry Stern", "zone": "Razorfen Downs"}, "classic": True},  # Goldthorn Tea
    24801: {"quests": [{"name": "Sharing the Knowledge", "zone": "Silithus", "level": 55, "side": ""}], "classic": True},  # Smoked Desert Dumplings
}


def payload(html):
    chunks = re.findall(r'self\.__next_f\.push\(\[1,("(?:[^"\\]|\\.)*")\]\)', html)
    return "".join(json.loads(chunk) for chunk in chunks)


def decode_at(text, marker, back_to_brace=False):
    at = text.find(marker)
    if at < 0:
        raise SystemExit("the page has no " + marker)
    if back_to_brace:
        at = at + len(marker) - 1
    value, _ = json.JSONDecoder().raw_decode(text, at)
    return value


def lua(value):
    if value is None:
        return "nil"
    if value is True:
        return "true"
    if value is False:
        return "false"
    if isinstance(value, (int, float)):
        return repr(value)
    return '"' + str(value).replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


def fields(pairs):
    return "{ " + ", ".join(k + " = " + lua(v) for k, v in pairs if v is not None and v != "") + " }"


def levels(level):
    if isinstance(level, list):
        return level[0], level[-1]
    return level, level


def main():
    html = open(sys.argv[1], encoding="utf-8").read()
    text = payload(html)
    rows = decode_at(text, '[{"spell":')
    items = decode_at(text, '"items":{', back_to_brace=True)

    def item(item_id):
        return items.get(str(item_id)) or {}

    out = []
    w = out.append
    w("-- GENERATED by tools/gen_data.py - do not edit by hand; edit the generator and run it again.")
    w("-- Source: foreverchanges.pro/professions/cooking, read " + datetime.date.today().isoformat() + ".")
    w("--")
    w("-- One entry per cooking recipe of WoW: Forever, in the order of the skill it needs:")
    w("--   spell   the recipe's spell id (what the client is asked about)      item    the dish's item id")
    w("--   learn / yellow / green / grey   the skill it is learned at and where its colour turns")
    w("--   recipe  the recipe ITEM that teaches it ({ id, name }) - none: it is taught, not read")
    w("--   vendors { npc, zone, side = \"A\" | \"H\" | nil, price (copper), limited }")
    w("--   quests  { name, level, zone, side }     drops { npc, zone, chance (%), min, max (level) }")
    w("--   favor   its price in Merchant's Favor   trainer  any Cooking trainer teaches it")
    w("--   taught  { npc, zone }: one NPC teaches it   classic  the source is Classic's, unconfirmed for Forever")
    w("--   new     a recipe Forever added")
    w("local _, ns = ...")
    w("")
    w("local Data = { recipes = {} }")
    w("ns.Data = Data")
    w('Data.source = "foreverchanges.pro/professions/cooking"')
    w('Data.readOn = "' + datetime.date.today().isoformat() + '"')
    w("")
    w("local function R(recipe)")
    w("    Data.recipes[#Data.recipes + 1] = recipe")
    w("end")
    w("")

    rows.sort(key=lambda r: (r["learn"], item(r["id"]).get("n") or ""))
    counts = {"recipes": 0, "vendor": 0, "quest": 0, "drop": 0, "trainer": 0, "taught": 0, "unknown": 0}
    for r in rows:
        dish = item(r["id"])
        name = dish.get("n")
        if not name:
            raise SystemExit("no name for item %s (spell %s)" % (r["id"], r["spell"]))
        source = dict(r.get("source") or {})
        over = OVERRIDES.get(r["spell"], {})
        source.update({k: v for k, v in over.items() if k in ("quests", "vendors", "drops")})
        formula = r.get("formula")
        level = None
        m = re.match(r"level (\d+)", r.get("kind") or "")
        if m:
            level = int(m.group(1))

        has_source = bool(source.get("vendors") or source.get("quests") or source.get("drops") or over.get("taught"))
        trainer = (not has_source) and (not formula) and (not r.get("isNew"))
        classic = bool(over.get("classic")) or source.get("read") == "classic"

        w("R({")
        w("    spell = %d, item = %d, name = %s, icon = %s," % (r["spell"], r["id"], lua(name), lua(dish.get("k"))))
        w("    learn = %d, yellow = %d, green = %d, grey = %d,%s%s" % (
            r["learn"], r["yellow"], r["green"], r["grey"],
            (" level = %d," % level) if level else "",
            " new = true," if r.get("isNew") else ""))
        if r.get("effect"):
            w("    effect = %s," % lua(r["effect"]))
        if r.get("count") and r["count"] > 1:
            w("    makes = %d," % r["count"])
        if formula:
            w("    recipe = %s," % fields([("id", formula["id"]), ("name", formula["name"])]))
        if trainer:
            w("    trainer = true,")
            counts["trainer"] += 1
        if over.get("taught"):
            w("    taught = %s," % fields([("npc", over["taught"]["npc"]), ("zone", over["taught"]["zone"])]))
            counts["taught"] += 1
        cost = source.get("cost")
        if cost and cost.get("currency") == "Merchant's Favor":
            w("    favor = %d," % cost["amount"])
        if source.get("vendors"):
            w("    vendors = {")
            for v in source["vendors"]:
                w("        %s," % fields([("npc", v["npc"]), ("zone", v.get("zone")), ("side", SIDE.get(v.get("side"))), ("price", v.get("price")), ("limited", v.get("limited") or None)]))
            w("    },")
            counts["vendor"] += 1
        if source.get("quests"):
            w("    quests = {")
            for q in source["quests"]:
                w("        %s," % fields([("name", q["name"]), ("level", q.get("level")), ("zone", q.get("zone")), ("side", SIDE.get(q.get("side")))]))
            w("    },")
            counts["quest"] += 1
        if source.get("drops"):
            w("    drops = {")
            for d in source["drops"]:
                lo, hi = levels(d.get("level"))
                w("        %s," % fields([("npc", d["npc"]), ("zone", d.get("zone")), ("chance", d.get("chance")), ("min", lo), ("max", hi)]))
            w("    },")
            counts["drop"] += 1
        if classic:
            w("    classic = true,")
        if not has_source and not trainer:
            counts["unknown"] += 1
        w("})")
        counts["recipes"] += 1

    w("")
    open(sys.argv[2], "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print(counts)


main()
