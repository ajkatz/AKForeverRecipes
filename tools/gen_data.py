# Writes Data/<Profession>.lua for every profession from the saved pages of foreverchanges.pro
# (tools/pages, see source.py), tools/binds.json (fetch_binds.py: how each recipe item binds) and
# tools/found_sources.json (research.py: sources the pages do not have, each with where it was found).
#
#   python tools/fetch_binds.py
#   python tools/research.py
#   python tools/gen_data.py
#
# What a page leaves open is filled by hand in OVERRIDES below, each marked as taken from Classic.
# Not shipped to players (.pkgmeta ignores tools/).
import datetime
import os
import re

import source

SIDE = {"a": "A", "h": "H"}
ROOT = os.path.dirname(source.HERE)

# Recipes a page lists without a source, whose Classic source is well known. classic = True marks the
# entry "as in Classic, not confirmed for Forever" in the window.
OVERRIDES = {
    13028: {"taught": {"npc": "Henry Stern", "zone": "Razorfen Downs"}, "classic": True},  # Goldthorn Tea
    24801: {"quests": [{"name": "Sharing the Knowledge", "zone": "Silithus", "level": 55, "side": ""}], "classic": True},  # Smoked Desert Dumplings
}

HEADER = """-- GENERATED by tools/gen_data.py - do not edit by hand; edit the generator and run it again.
-- Source: foreverchanges.pro/professions/%s (recipes) and Wowhead's Forever tooltips (how recipe items
-- bind), read %s.
--
-- One entry per recipe, in the order of the skill it needs (the fields are described in Data.lua). The
-- entries are built the first time somebody asks for this profession - a character without it never pays
-- for them.
local _, ns = ...

ns.Data.Register({ key = %s, name = %s, line = %d, short = %s, icon = %s, count = %d, readOn = %s }, function(R, I)
-- the reagents these recipes name: I(item id, name, icon)
%s
"""


def lua(value):
    if value is None:
        return "nil"
    if value is True:
        return "true"
    if value is False:
        return "false"
    if isinstance(value, (int, float)):
        return repr(value)
    return '"' + str(value).replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


def fields(pairs):
    return "{ " + ", ".join(k + " = " + lua(v) for k, v in pairs if v is not None and v != "") + " }"


def levels(level):
    if isinstance(level, list):
        return level[0], level[-1]
    return level, level


VIA = {"questie": "Questie", "wowhead": "Wowhead"}


def write_profession(prof, binds, today, totals, found):
    key, name, line, page, short, icon = prof
    rows, skipped = source.load(key, binds, found)
    found_sources, auto = found.get("sources", {}), set(found.get("auto", []))
    rows.sort(key=lambda r: (r["learn"], r["name"], r["spell"]))
    out = []
    w = out.append
    used_items = {}   # reagent and station items: id -> (name, icon)
    no_name = 0
    counts = {"recipes": 0, "vendor": 0, "quest": 0, "drop": 0, "trainer": 0, "auto": 0, "found": 0, "unknown": 0, "bop": 0, "nobind": 0}
    for r in rows:
        src = dict(r["source"])
        over = OVERRIDES.get(r["spell"], {})
        src.update({k: v for k, v in over.items() if k in ("quests", "vendors", "drops")})
        formula = r["formula"]
        # what the research found: a source for a recipe that had none, or another quest for one that had
        extra = found_sources.get(str(formula["id"])) if formula else None
        via = None
        if extra and extra.get("adds"):
            src["quests"] = list(src.get("quests") or []) + extra["quests"]
        elif extra:
            for k in ("vendors", "quests", "drops", "world", "objects", "cost", "somewhere"):
                if extra.get(k):
                    src[k] = extra[k]
            via = ", ".join(VIA[w] for w in extra.get("from", []) if w in VIA) or None
            counts["found"] += 1

        level = None
        kind = r["kind"]
        m = re.match(r"^level (\d+)$", kind)
        if m:
            level, kind = int(m.group(1)), ""
        # what the made thing gives, one entry per line of an opened card: its stats, then its effect - an
        # effect that is itself a row of bonuses ("+9 Defense Rating +9 Spell Power") is taken apart
        stats = list(r["stats"])
        effect = r["effect"]
        if re.match(r"^\+\d", effect):
            stats += re.split(r" (?=\+\d)", effect)
        elif effect:
            stats.append(effect)

        vendors, quests = src.get("vendors") or [], src.get("quests") or []
        drops = list(src.get("drops") or [])
        for thing in src.get("objects") or []:
            drops.append({"npc": thing.get("name"), "zone": thing.get("zone"), "object": True})
        world = src.get("world")
        somewhere = src.get("somewhere") or []
        has_source = bool(vendors or quests or drops or world or somewhere or src.get("trainers") or src.get("capitals") or src.get("made") or over.get("taught"))
        by_quest = r["byQuest"] and not quests
        comes_with_skill = r["spell"] in auto and not formula and not has_source and not by_quest
        trainer = (not has_source) and (not formula) and (not by_quest) and (not comes_with_skill)
        classic = bool(over.get("classic")) or src.get("read") == "classic"

        w("R({")
        w("    spell = %d,%s name = %s, icon = %s," % (r["spell"], (" item = %d," % r["item"]) if r["item"] else "", lua(r["name"]), lua(r["icon"])))
        w("    learn = %d, yellow = %d, green = %d, grey = %d,%s%s" % (
            r["learn"], r["yellow"], r["green"], r["grey"],
            (" level = %d," % level) if level else "",
            " new = true," if r["new"] else ""))
        if kind:
            w("    kind = %s," % lua(kind))
        if stats:
            w("    stats = { %s }," % ", ".join(lua(s) for s in stats))
        if r["reagents"]:
            for g in r["reagents"]:
                if g["name"]:
                    used_items[g["id"]] = (g["name"], g["icon"])
                else:
                    no_name += 1
            w("    reagents = { %s }," % ", ".join("{ %d, %d }" % (g["id"], g["count"]) for g in r["reagents"]))
        if r["station"] and r["station"]["name"]:
            used_items[r["station"]["id"]] = (r["station"]["name"], None)
            w("    station = %d," % r["station"]["id"])
        if r.get("spec"):
            w("    spec = %s," % lua(r["spec"]))
        if r["count"] > 1:
            w("    makes = %d," % r["count"])
        if formula:
            known = binds.get(str(formula["id"])) or {}
            bind = known.get("bind")
            if bind is None and formula.get("bound") is not None:
                bind = "pickup" if formula["bound"] else "none"
            if bind is None:
                counts["nobind"] += 1
            w("    recipe = %s," % fields([("id", formula["id"]), ("name", formula["name"]), ("bop", True if bind == "pickup" else None), ("bind", "?" if bind is None else None)]))
            counts["bop"] += 1 if bind == "pickup" else 0
        if trainer:
            w("    trainer = true,%s" % (" unsure = true," if r["new"] else ""))
            counts["trainer"] += 1
        if comes_with_skill:
            w("    auto = true,")
            counts["auto"] += 1
        if by_quest:
            w("    byQuest = true,")
        if somewhere:
            w("    somewhere = { %s }," % ", ".join(k + " = true" for k in somewhere))
        if via:
            w("    via = %s," % lua(via))
        if over.get("taught"):
            w("    taught = %s," % fields([("npc", over["taught"]["npc"]), ("zone", over["taught"]["zone"])]))
        cost = src.get("cost")
        if cost and cost.get("currency") == "Merchant's Favor":
            w("    favor = %d," % cost["amount"])
        if src.get("trainers"):
            w("    trainersSell = %d," % src["trainers"])
        if src.get("capitals"):
            w("    capitals = true,")
        if world:
            w("    world = { %d, %d }," % (world[0], world[-1]))
        if src.get("made"):
            w("    made = { %s }," % ", ".join(lua(x) for x in src["made"]))
        if vendors:
            w("    vendors = {")
            for v in vendors:
                w("        %s," % fields([("npc", v["npc"]), ("zone", v.get("zone")), ("side", SIDE.get(v.get("side"))), ("price", v.get("price")), ("limited", v.get("limited") or None)]))
            w("    },")
            counts["vendor"] += 1
        if quests:
            w("    quests = {")
            for q in quests:
                w("        %s," % fields([("name", q["name"]), ("level", q.get("level")), ("zone", q.get("zone")), ("side", SIDE.get(q.get("side")))]))
            w("    },")
            counts["quest"] += 1
        if drops:
            w("    drops = {")
            for d in drops:
                lo, hi = levels(d.get("level"))
                w("        %s," % fields([("npc", d["npc"]), ("zone", d.get("zone")), ("chance", d.get("chance")), ("min", lo), ("max", hi), ("object", d.get("object"))]))
            w("    },")
        if drops or world:
            counts["drop"] += 1
        if classic:
            w("    classic = true,")
        if not has_source and not trainer and not by_quest and not comes_with_skill:
            counts["unknown"] += 1
        w("})")
        counts["recipes"] += 1

    item_lines = "\n".join("I(%d, %s%s)" % (i, lua(n), (", " + lua(k)) if k else "") for i, (n, k) in sorted(used_items.items()))
    counts["reagent items"] = len(used_items)
    counts["reagents without a name"] = no_name
    head = HEADER % (page, today, lua(key), lua(name), line, lua(short), lua(icon), counts["recipes"], lua(today), item_lines)
    file_name = name.replace(" ", "") + ".lua"
    os.makedirs(os.path.join(ROOT, "Data"), exist_ok=True)
    open(os.path.join(ROOT, "Data", file_name), "w", encoding="utf-8", newline="\n").write(head + "\n".join(out) + "\nend)\n")
    print("%-15s %s  skipped %d %s" % (key, counts, len(skipped), skipped[:2]))
    for k, v in counts.items():
        totals[k] = totals.get(k, 0) + v
    return file_name


def main():
    binds = source.load_binds()
    today = datetime.date.today().isoformat()
    totals = {}
    found = source.load_found()
    files = [write_profession(prof, binds, today, totals, found) for prof in source.PROFESSIONS]
    print("total", totals)
    print("TOC lines:")
    for name in files:
        print("Data\\" + name)


main()
