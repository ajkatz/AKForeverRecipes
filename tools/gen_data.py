# Writes Data/<Profession>.lua for every profession from the saved pages of foreverchanges.pro
# (tools/pages, see source.py), tools/binds.json (fetch_binds.py: how each recipe item binds) and
# tools/found_sources.json (research.py: sources the pages do not have, each with where it was found)
# and tools/trainer_costs.json (what a trainer asks for each recipe it teaches: { "<spell id>": copper },
# read 2026-11-13 in a browser from Wowhead's Forever spell lists, wowhead.com/forever/spells/professions/
# <profession> and secondary-skills/<cooking|first-aid>, the "trainingcost" of every row) and
# tools/specializations.json (the specialization a recipe needs: { "<spell id>": <the specialization's
# spell id> }, read 2026-11-14 from the same Wowhead lists, the "specialization" of every row - Leatherworking,
# Blacksmithing and Engineering have them; the profession pages only know Engineering's) and
# tools/wowhead_drops.json (creatures that drop a recipe item the pages only name one faction's vendor or
# quest for, read 2026-11-15 from Wowhead's Forever item pages - without them the other faction never saw
# the recipe) and tools/trainer_teachers.json (recipes only a profession's Master trainers teach - every
# profession, read 2026-11-18 from Wowhead's Forever NPC pages; the file says how, and which
# professions are still unread) and tools/rep_requirements.json (gen_rep.py: the reputation standing a
# recipe item asks for - the client's own item table).
#
#   python tools/fetch_binds.py
#   python tools/research.py
#   python tools/gen_rep.py
#   python tools/gen_data.py
#
# What a page leaves open is filled by hand in OVERRIDES below, each marked as taken from Classic.
# Not shipped to players (.pkgmeta ignores tools/).
import datetime
import json
import os
import re

import source

SIDE = {"a": "A", "h": "H"}
ROOT = os.path.dirname(source.HERE)

# Recipes a page lists without a source, whose Classic source is well known. classic = True marks the
# entry "as in Classic, not confirmed for Forever" in the window.
OVERRIDES = {
    13028: {"taught": {"npc": "Henry Stern", "zone": "Razorfen Downs"}, "classic": True},  # Goldthorn Tea
    24801: {"quests": [{"name": "Sharing the Knowledge", "zone": "Silithus", "level": 55, "side": ""}], "classic": True},  # Smoked Desert Dumplings
}

HEADER = """-- GENERATED by tools/gen_data.py - do not edit by hand; edit the generator and run it again.
-- Source: foreverchanges.pro/professions/%s (recipes) and Wowhead's Forever tooltips (how recipe items
-- bind), read %s.
--
-- One entry per recipe, in the order of the skill it needs (the fields are described in Data.lua). The
-- entries are built the first time somebody asks for this profession - a character without it never pays
-- for them.
local _, ns = ...

ns.Data.Register({ key = %s, name = %s, line = %d, short = %s, icon = %s, count = %d, readOn = %s }, function(R, I)
-- the reagents these recipes name: I(item id, name, icon)
%s
"""


def lua(value):
    if value is None:
        return "nil"
    if value is True:
        return "true"
    if value is False:
        return "false"
    if isinstance(value, (int, float)):
        return repr(value)
    return '"' + str(value).replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


def fields(pairs):
    return "{ " + ", ".join(k + " = " + lua(v) for k, v in pairs if v is not None and v != "") + " }"


def levels(level):
    if isinstance(level, list):
        return level[0], level[-1]
    return level, level


VIA = {"questie": "Questie", "wowhead": "Wowhead"}


def write_profession(prof, binds, today, totals, found):
    key, name, line, page, short, icon = prof
    rows, skipped = source.load(key, binds, found)
    found_sources, auto = found.get("sources", {}), set(found.get("auto", []))
    rows.sort(key=lambda r: (r["learn"], r["name"], r["spell"]))
    out = []
    w = out.append
    used_items = {}   # reagent and station items: id -> (name, icon)
    no_name = 0
    counts = {"recipes": 0, "vendor": 0, "quest": 0, "drop": 0, "trainer": 0, "auto": 0, "found": 0, "unknown": 0, "bop": 0, "nobind": 0}
    for r in rows:
        src = dict(r["source"])
        over = OVERRIDES.get(r["spell"], {})
        src.update({k: v for k, v in over.items() if k in ("quests", "vendors", "drops")})
        formula = r["formula"]
        # what the research found: a source for a recipe that had none, or another quest for one that had
        extra = found_sources.get(str(formula["id"])) if formula else None
        via = None
        if extra and extra.get("adds"):
            src["quests"] = list(src.get("quests") or []) + extra["quests"]
        elif extra:
            for k in ("vendors", "quests", "drops", "world", "objects", "cost", "somewhere"):
                if extra.get(k):
                    src[k] = extra[k]
            via = ", ".join(VIA[w] for w in extra.get("from", []) if w in VIA) or None
            counts["found"] += 1
        # a creature Wowhead's item page saw dropping the recipe item, where the pages name no drop
        more = WOWHEAD_DROPS.get(str(formula["id"])) if formula else None
        on_wowhead = bool(more and not src.get("drops"))
        if on_wowhead:
            src["drops"] = more
            counts["wowhead drop"] = counts.get("wowhead drop", 0) + 1

        level = None
        kind = r["kind"]
        m = re.match(r"^level (\d+)$", kind)
        if m:
            level, kind = int(m.group(1)), ""
        # what the made thing gives, one entry per line of an opened card: its stats, then its effect - an
        # effect that is itself a row of bonuses ("+9 Defense Rating +9 Spell Power") is taken apart
        stats = list(r["stats"])
        effect = r["effect"]
        if re.match(r"^\+\d", effect):
            stats += re.split(r" (?=\+\d)", effect)
        elif effect:
            stats.append(effect)

        vendors, quests = src.get("vendors") or [], src.get("quests") or []
        drops = list(src.get("drops") or [])
        for thing in src.get("objects") or []:
            drops.append({"npc": thing.get("name"), "zone": thing.get("zone"), "object": True})
        world = src.get("world")
        somewhere = src.get("somewhere") or []
        has_source = bool(vendors or quests or drops or world or somewhere or src.get("trainers") or src.get("capitals") or src.get("made") or over.get("taught"))
        by_quest = r["byQuest"] and not quests
        comes_with_skill = r["spell"] in auto and not formula and not has_source and not by_quest
        trainer = (not has_source) and (not formula) and (not by_quest) and (not comes_with_skill)
        # (a recipe whose item page was read is no longer "as in Classic": the page's sold-by list named the
        # same vendors and its drop was counted on Forever)
        classic = (bool(over.get("classic")) or src.get("read") == "classic" or r["spell"] in CLASSIC_TEACHERS) and not on_wowhead

        w("R({")
        w("    spell = %d,%s name = %s, icon = %s," % (r["spell"], (" item = %d," % r["item"]) if r["item"] else "", lua(r["name"]), lua(r["icon"])))
        w("    learn = %d, yellow = %d, green = %d, grey = %d,%s%s" % (
            r["learn"], r["yellow"], r["green"], r["grey"],
            (" level = %d," % level) if level else "",
            " new = true," if r["new"] else ""))
        if kind:
            w("    kind = %s," % lua(kind))
        if stats:
            w("    stats = { %s }," % ", ".join(lua(s) for s in stats))
        if r["reagents"]:
            for g in r["reagents"]:
                if g["name"]:
                    used_items[g["id"]] = (g["name"], g["icon"])
                else:
                    no_name += 1
            w("    reagents = { %s }," % ", ".join("{ %d, %d }" % (g["id"], g["count"]) for g in r["reagents"]))
        if r["station"] and r["station"]["name"]:
            used_items[r["station"]["id"]] = (r["station"]["name"], None)
            w("    station = %d," % r["station"]["id"])
        spec = SPEC_WORDS.get(SPECIALIZATIONS.get(str(r["spell"]))) or r.get("spec")
        if spec:
            w("    spec = %s," % lua(spec))
            counts["spec"] = counts.get("spec", 0) + 1
        if r["count"] > 1:
            w("    makes = %d," % r["count"])
        if formula:
            known = binds.get(str(formula["id"])) or {}
            bind = known.get("bind")
            if bind is None and formula.get("bound") is not None:
                bind = "pickup" if formula["bound"] else "none"
            if bind is None:
                counts["nobind"] += 1
            item_line = fields([("id", formula["id"]), ("name", formula["name"]), ("bop", True if bind == "pickup" else None), ("bind", "?" if bind is None else None)])
            # "Requires Timbermaw Hold - Honored": { the faction's id, its name, the standing (4 Friendly .. 7 Exalted) }
            need = REP.get(str(formula["id"]))
            if need and need.get("name") and 4 <= need["standing"] <= 7:
                item_line = item_line[:-2] + ", rep = { %d, %s, %d } }" % (need["faction"], lua(need["name"]), need["standing"])
                counts["rep"] = counts.get("rep", 0) + 1
            w("    recipe = %s," % item_line)
            counts["bop"] += 1 if bind == "pickup" else 0
        if trainer:
            cost = TRAINER_COSTS.get(str(r["spell"]))
            guess = r["new"] and r["spell"] not in CONFIRMED  # a trainer's own list had it: no guess
            w("    trainer = true,%s%s" % (" unsure = true," if guess else "", (" cost = %d," % cost) if cost else ""))
            counts["confirmed"] = counts.get("confirmed", 0) + (1 if r["new"] and not guess else 0)
            counts["cost"] = counts.get("cost", 0) + (1 if cost else 0)
            counts["trainer"] += 1
        teachers = TEACHERS.get(r["spell"])
        if teachers and not trainer:
            raise SystemExit("%s (%d) has named trainers in trainer_teachers.json but is not a trainer's recipe" % (r["name"], r["spell"]))
        if teachers:
            w("    teachers = {")
            for t in teachers:
                w("        %s," % fields([("npc", t["npc"]), ("zone", t.get("zone")), ("side", SIDE.get(t.get("side"))), ("title", t.get("title")), ("faction", t.get("faction"))]))
            w("    },")
            counts["named trainers"] = counts.get("named trainers", 0) + 1
        if comes_with_skill:
            w("    auto = true,")
            counts["auto"] += 1
        if by_quest:
            w("    byQuest = true,")
        if somewhere:
            w("    somewhere = { %s }," % ", ".join(k + " = true" for k in somewhere))
        if via:
            w("    via = %s," % lua(via))
        if over.get("taught"):
            w("    taught = %s," % fields([("npc", over["taught"]["npc"]), ("zone", over["taught"]["zone"])]))
        cost = src.get("cost")
        if cost and cost.get("currency") == "Merchant's Favor":
            w("    favor = %d," % cost["amount"])
        if src.get("trainers"):
            w("    trainersSell = %d," % src["trainers"])
        if src.get("capitals"):
            w("    capitals = true,")
        if world:
            w("    world = { %d, %d }," % (world[0], world[-1]))
        if src.get("made"):
            w("    made = { %s }," % ", ".join(lua(x) for x in src["made"]))
        if vendors:
            w("    vendors = {")
            for v in vendors:
                w("        %s," % fields([("npc", v["npc"]), ("zone", v.get("zone")), ("side", SIDE.get(v.get("side"))), ("price", v.get("price")), ("limited", v.get("limited") or None)]))
            w("    },")
            counts["vendor"] += 1
        if quests:
            w("    quests = {")
            for q in quests:
                w("        %s," % fields([("name", q["name"]), ("level", q.get("level")), ("zone", q.get("zone")), ("side", SIDE.get(q.get("side")))]))
            w("    },")
            counts["quest"] += 1
        if drops:
            w("    drops = {")
            for d in drops:
                lo, hi = levels(d.get("level"))
                w("        %s," % fields([("npc", d["npc"]), ("zone", d.get("zone")), ("chance", d.get("chance")), ("min", lo), ("max", hi), ("object", d.get("object")), ("fished", d.get("fished"))]))
            w("    },")
        if drops or world:
            counts["drop"] += 1
        if classic:
            w("    classic = true,")
        if not has_source and not trainer and not by_quest and not comes_with_skill:
            counts["unknown"] += 1
        w("})")
        counts["recipes"] += 1

    item_lines = "\n".join("I(%d, %s%s)" % (i, lua(n), (", " + lua(k)) if k else "") for i, (n, k) in sorted(used_items.items()))
    counts["reagent items"] = len(used_items)
    counts["reagents without a name"] = no_name
    head = HEADER % (page, today, lua(key), lua(name), line, lua(short), lua(icon), counts["recipes"], lua(today), item_lines)
    file_name = name.replace(" ", "") + ".lua"
    os.makedirs(os.path.join(ROOT, "Data"), exist_ok=True)
    open(os.path.join(ROOT, "Data", file_name), "w", encoding="utf-8", newline="\n").write(head + "\n".join(out) + "\nend)\n")
    print("%-15s %s  skipped %d %s" % (key, counts, len(skipped), skipped[:2]))
    for k, v in counts.items():
        totals[k] = totals.get(k, 0) + v
    return file_name


_SPECS = os.path.join(source.HERE, "specializations.json")
SPECIALIZATIONS = json.load(open(_SPECS, encoding="utf-8")) if os.path.exists(_SPECS) else {}
# the specialization's spell -> the word the tables carry (Lookup.lua has the whole names)
SPEC_WORDS = {
    20219: "Gnomish", 20222: "Goblin",
    10656: "Dragonscale", 10658: "Elemental", 10660: "Tribal",
    9788: "Armorsmith", 9787: "Weaponsmith", 17039: "Swordsmith", 17040: "Hammersmith", 17041: "Axesmith",
}
_REP = os.path.join(source.HERE, "rep_requirements.json")
REP = json.load(open(_REP, encoding="utf-8")) if os.path.exists(_REP) else {}
_DROPS = os.path.join(source.HERE, "wowhead_drops.json")
WOWHEAD_DROPS = json.load(open(_DROPS, encoding="utf-8")).get("drops", {}) if os.path.exists(_DROPS) else {}
_COSTS = os.path.join(source.HERE, "trainer_costs.json")
TRAINER_COSTS = json.load(open(_COSTS, encoding="utf-8")) if os.path.exists(_COSTS) else {}
# recipes not every trainer teaches: spell id -> the trainers who do (tools/trainer_teachers.json says where
# each group was read)
_TEACHERS = os.path.join(source.HERE, "trainer_teachers.json")
_TEACHERS_FILE = json.load(open(_TEACHERS, encoding="utf-8")) if os.path.exists(_TEACHERS) else {}
TEACHERS = {}
CLASSIC_TEACHERS = set()  # recipes whose named trainers are Classic's, not read for Forever
for _group in _TEACHERS_FILE.get("groups", []):
    for _spell in _group["spells"]:
        TEACHERS[int(_spell)] = _group["teachers"]
        if _group.get("classic"):
            CLASSIC_TEACHERS.add(int(_spell))
# recipes new in Forever that a trainer's list was seen to hold: "Any trainer", no longer "Probably"
CONFIRMED = set(_TEACHERS_FILE.get("confirmed", {}).get("spells", []))


def main():
    binds = source.load_binds()
    # the day the profession pages were saved, not the day this ran
    pages = os.path.join(source.HERE, "pages")
    saved = max(os.path.getmtime(os.path.join(pages, f)) for f in os.listdir(pages) if f.endswith(".html"))
    today = datetime.date.fromtimestamp(saved).isoformat()
    totals = {}
    found = source.load_found()
    files = [write_profession(prof, binds, today, totals, found) for prof in source.PROFESSIONS]
    print("total", totals)
    print("TOC lines:")
    for name in files:
        print("Data\\" + name)


main()
